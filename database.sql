-- قاعدة بيانات Supabase
create table if not exists public.survey_responses (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  department text not null,
  quality integer not null check (quality between 1 and 5),
  reception integer not null check (reception between 1 and 5),
  information integer not null check (information between 1 and 5),
  processing_speed integer not null check (processing_speed between 1 and 5),
  service_quality integer not null check (service_quality between 1 and 5),
  response_time text not null,
  resolved text not null,
  comment text
);

alter table public.survey_responses enable row level security;

-- المرتفق يستطيع الإرسال فقط
create policy "public can insert survey"
on public.survey_responses for insert
to anon
with check (true);

-- لا تسمح للزائر بقراءة النتائج
-- القراءة للمسؤول تتم بواسطة مستخدم Supabase Auth مع السياسة التالية:
create policy "authenticated can read survey"
on public.survey_responses for select
to authenticated
using (true);

